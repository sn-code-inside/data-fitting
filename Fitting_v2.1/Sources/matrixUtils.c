/*---------------------------------------------------------------
 *	determinant_2x2()
 *--------------------------------------------------------------*/
double determinant_2x2( double** a )
{
	return diffOfProducts( a[0][0], a[1][1], a[0][1], a[1][0] );
}
double determinant_2x2_old( double **a)
{
	return a[0][0] * a[1][1] - a[0][1] * a[1][0];
}

/*---------------------------------------------------------------
 * determinant_3x3_from_cofactor() as 
 * inner rproduct of first row and first cofactor column 
 * (b[0][0], b[1][0], b[2][0] = C00, C01, C02) —
 * saves double minor computation 
 *--------------------------------------------------------------*/
double
determinant_3x3_from_cofactor( double** a, double** b )
{
	double det = a[0][2] * b[2][0];
	det = fma( a[0][1], b[1][0], det );
	det = fma( a[0][0], b[0][0], det );
	return det;
}

/*---------------------------------------------------------------
 *	determinant_3x3()
 *--------------------------------------------------------------*/
double
determinant_3x3( double **a)
{
	// a11*a22 - a21*a12
	double m0 = diffOfProducts( a[1][1], a[2][2], a[2][1], a[1][2] ); 
	// a10*a22 - a20*a12
	double m1 = diffOfProducts( a[1][0], a[2][2], a[2][0], a[1][2] ); 
	// a10*a21 - a20*a11
	double m2 = diffOfProducts( a[1][0], a[2][1], a[2][0], a[1][1] ); 

	double t0 = a[0][0] * m0;
	double t1 = a[0][1] * m1;
	double t2 = a[0][2] * m2;

	// Kahan-Summation für r = t0 - t1 + t2
	double sum = t0, c = 0.0, y, t;
	y = -t1 - c; t = sum + y; c = (t - sum) - y; sum = t;
	y = t2 - c; t = sum + y; /*c = (t - sum) - y;*/ sum = t;

	return sum;
}

